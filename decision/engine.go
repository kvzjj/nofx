func parseFullDecisionResponse(aiResponse string, accountEquity float64, riskControl store.RiskControlConfig, entryPrices map[string]float64) (*FullDecision, error) {
	cotTrace := extractCoTTrace(aiResponse)

	decisions, err := extractDecisions(aiResponse)
	if err != nil {
		return &FullDecision{
			CoTTrace:  cotTrace,
			Decisions: []Decision{},
		}, fmt.Errorf("failed to extract decisions: %w", err)
	}

	validDecisions, validationErrors := validateAndFilterDecisions(decisions, accountEquity, riskControl, entryPrices)
	if len(validDecisions) == 0 && len(validationErrors) > 0 {
		return &FullDecision{
			CoTTrace:         cotTrace,
			Decisions:        []Decision{},
			ValidationErrors: validationErrors,
		}, fmt.Errorf("all decisions failed validation: %s", strings.Join(validationErrors, "; "))
	}

	return &FullDecision{
		CoTTrace:         cotTrace,
		Decisions:        validDecisions,
		ValidationErrors: validationErrors,
	}, nil
}

func extractCoTTrace(response string) string {
	if match := reReasoningTag.FindStringSubmatch(response); match != nil && len(match) > 1 {
		logger.Infof("✓ Extracted reasoning chain using <reasoning> tag")
		return strings.TrimSpace(match[1])
	}

	if decisionIdx := strings.Index(response, "<decision>"); decisionIdx > 0 {
		logger.Infof("✓ Extracted content before <decision> tag as reasoning chain")
		return strings.TrimSpace(response[:decisionIdx])
	}

	// Legacy fallback: separate prose from a JSON decision array. Only treat
	// "[" as the boundary when it opens a decision array ("[{"), so bracketed
	// prose like "RSI [14]" or "momentum [1h]" does not truncate the trace.
	for i := 0; i < len(response); i++ {
		if response[i] != '[' {
			continue
		}
		j := i + 1
		for j < len(response) && (response[j] == ' ' || response[j] == '\t' || response[j] == '\r' || response[j] == '\n') {
			j++
		}
		if i > 0 && j < len(response) && response[j] == '{' {
			logger.Infof("⚠️  Extracted reasoning chain using legacy format ([{ separator)")
			return strings.TrimSpace(response[:i])
		}
	}

	return strings.TrimSpace(response)
}

func extractDecisions(response string) ([]Decision, error) {
	s := removeInvisibleRunes(response)
	s = strings.TrimSpace(s)
	s = fixMissingQuotes(s)

	var jsonPart string
	if match := reDecisionTag.FindStringSubmatch(s); match != nil && len(match) > 1 {
		jsonPart = strings.TrimSpace(match[1])
		logger.Infof("✓ Extracted JSON using <decision> tag")
	} else {
		jsonPart = s
		logger.Infof("⚠️  <decision> tag not found, searching JSON in full text")
	}

	jsonPart = fixMissingQuotes(jsonPart)

	decisions, jsonContent, decodeErr := decodeDecisionsFromText(jsonPart)
	if decodeErr == nil {
		if len(decisions) == 0 {
			return []Decision{{
				Symbol:    "ALL",
				Action:    "wait",
				Reasoning: "Model returned an empty decision list; entering safe wait",
			}}, nil
		}
		for i := range decisions {
			normalizeDecision(&decisions[i])
		}
		return decisions, nil
	}

	if jsonContent == "" {
		logger.Infof("⚠️  [SafeFallback] AI didn't output JSON decision, entering safe wait mode")

		cotSummary := jsonPart
		if len(cotSummary) > 240 {
			cotSummary = cotSummary[:240] + "..."
		}

		fallbackDecision := Decision{
			Symbol:    "ALL",
			Action:    "wait",
			Reasoning: fmt.Sprintf("Model didn't output structured JSON decision, entering safe wait; summary: %s", cotSummary),
		}

		return []Decision{fallbackDecision}, nil
	}

	return nil, fmt.Errorf("JSON parsing failed: %w\nJSON content: %s", decodeErr, jsonContent)
}

func normalizeDecision(d *Decision) {
	d.Symbol = strings.ToUpper(strings.TrimSpace(d.Symbol))
	d.Symbol = strings.NewReplacer("/", "", "-", "", "_", "", " ", "").Replace(d.Symbol)

	d.Action = strings.ToLower(strings.TrimSpace(d.Action))
	d.Action = strings.NewReplacer("-", "_", " ", "_").Replace(d.Action)
	for strings.Contains(d.Action, "__") {
		d.Action = strings.ReplaceAll(d.Action, "__", "_")
	}
	d.Reasoning = strings.TrimSpace(d.Reasoning)
}

